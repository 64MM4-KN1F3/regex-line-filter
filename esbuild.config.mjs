import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";
import path from "path";
import dotenv from "dotenv";

dotenv.config();

const banner =
  `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  plugins: [{
    name: 'copy-to-obsidian',
    setup(build) {
      build.onEnd(() => {
        const obsidianPath = process.env.OBSIDIAN_PLUGINS_PATH;
        if (!obsidianPath) return;

        const targetDir = path.join(obsidianPath, 'regex-line-filter-dev');

        try {
          if (!fs.existsSync(targetDir)) {
            fs.mkdirSync(targetDir, { recursive: true });
          }

          const files = ['main.js', 'styles.css', 'manifest.json'];

          files.forEach(file => {
            const src = path.join(process.cwd(), file);
            const dest = path.join(targetDir, file);

            if (fs.existsSync(src)) {
              if (file === 'manifest.json') {
                const manifest = JSON.parse(fs.readFileSync(src, 'utf8'));
                manifest.id += '-dev';
                manifest.name += ' (Dev)';
                fs.writeFileSync(dest, JSON.stringify(manifest, null, 2));
                console.log(`Copied and modified ${file} to ${dest}`);
              } else {
                fs.copyFileSync(src, dest);
                console.log(`Copied ${file} to ${dest}`);
              }
            }
          });
        } catch (e) {
          console.error(`Failed to copy files to ${targetDir}:`, e);
        }
      });
    },
  }],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
